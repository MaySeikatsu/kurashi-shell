# Regenerates nix/icon-names.txt (W39-block): every Material Symbols ligature name the repo mentions as a quoted string in
# frontend/, settings/, mods/ and crates/ (QML, JS, Rust, TOML, JSON), plus every name that starts with a prefix the code
# builds names from ("battery_" + n + "_bar"). A superset is fine: a stray word that is also an icon costs a few hundred
# bytes; a missing icon draws as its letters.
#   nix shell --impure --expr 'let p = (builtins.getFlake "nixpkgs").legacyPackages.x86_64-linux;
#     in p.python3.withPackages (ps: [ ps.fonttools ])' -c python3 -I nix/icon-names.py \
#     "$(nix build --no-link --print-out-paths nixpkgs#material-symbols)/share/fonts/truetype/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf" . \
#     > nix/icon-names.txt
import os
import re
import sys

from fontTools.ttLib import TTFont

font = TTFont(sys.argv[1], lazy=True)
repo = sys.argv[2]
rev = {g: chr(c) for c, g in font.getBestCmap().items()}
names = set()
for lookup in font["GSUB"].table.LookupList.Lookup:
    for st in lookup.SubTable:
        if st.LookupType == 7:
            st = st.ExtSubTable
        for first, ligs in getattr(st, "ligatures", {}).items():
            for lig in ligs:
                try:
                    names.add("".join(rev[c] for c in [first] + list(lig.Component)))
                except KeyError:
                    pass
used, prefixes = set(), set()
for d in ["frontend", "settings", "mods", "crates"]:
    for root, _, files in os.walk(os.path.join(repo, d)):
        if "/shots" in root or "/target" in root or "/golden" in root:
            continue
        for f in files:
            if not f.endswith((".qml", ".js", ".rs", ".toml", ".json")):
                continue
            t = open(os.path.join(root, f), errors="ignore").read()
            used |= {m for m in re.findall(r'["\']([a-z0-9_]{2,60})["\']', t) if m in names}
            prefixes |= set(re.findall(r'["\']([a-z0-9_]{2,40}_)["\']\s*\+', t))
for p in prefixes:
    used |= {n for n in names if n.startswith(p)}
print("# Generated by nix/icon-names.py: the Material Symbols names kurashi-shell draws (%d)." % len(used))
print("\n".join(sorted(used)))
