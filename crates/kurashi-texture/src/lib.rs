/// The materials (`theme.texture.kind` without `none`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Kind {
    Paper,
    PaperDots,
    PaperLines,
    PaperGrid,
    Fabric,
    Wool,
    Stone,
    Halftone,
    Metal,
    Leather,
    Wood,
    Paint,
}

impl Kind {
    pub const ALL: [Kind; 12] = [
        Kind::Paper,
        Kind::PaperDots,
        Kind::PaperLines,
        Kind::PaperGrid,
        Kind::Fabric,
        Kind::Wool,
        Kind::Stone,
        Kind::Halftone,
        Kind::Metal,
        Kind::Leather,
        Kind::Wood,
        Kind::Paint,
    ];

    /// The config value (`paper_dots`); `None` for an unknown name and for `none`.
    pub fn parse(s: &str) -> Option<Kind> {
        Kind::ALL.into_iter().find(|k| k.name() == s)
    }

    pub fn name(self) -> &'static str {
        match self {
            Kind::Paper => "paper",
            Kind::PaperDots => "paper_dots",
            Kind::PaperLines => "paper_lines",
            Kind::PaperGrid => "paper_grid",
            Kind::Fabric => "fabric",
            Kind::Wool => "wool",
            Kind::Stone => "stone",
            Kind::Halftone => "halftone",
            Kind::Metal => "metal",
            Kind::Leather => "leather",
            Kind::Wood => "wood",
            Kind::Paint => "paint",
        }
    }
}

/// Which palette role a kind's ink takes (the daemon resolves it to a colour, token `texture.ink`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InkRole {
    /// No ink in this kind.
    None,
    /// Rulings, grids, dots: the palette's secondary role (a notebook's blue lines).
    Secondary,
    /// Print and pigment: the text colour.
    OnSurface,
}

/// How a kind reflects light, and what its ink is.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Material {
    /// Specular amount (0 matte paper … 1 polished metal).
    pub gloss: f32,
    /// Specular exponent.
    pub shininess: f32,
    pub ink_role: InkRole,
    /// The ink's opacity at full coverage (A = 255), before the user's strength.
    pub ink_alpha: f32,
}

/// One generated tile.
#[derive(Clone, Debug, PartialEq)]
pub struct Tile {
    /// Side in device pixels.
    pub size: u32,
    /// The logical pixels the tile covers at `theme.texture.scale` 1 (`size / device_scale`).
    pub logical: f32,
    /// Row-major RGBA8, `size * size * 4` bytes, in the layout of the module docs.
    pub rgba: Vec<u8>,
}

impl Tile {
    pub fn texel(&self, x: u32, y: u32) -> [u8; 4] {
        let i = ((y % self.size) * self.size + (x % self.size)) as usize * 4;
        [
            self.rgba[i],
            self.rgba[i + 1],
            self.rgba[i + 2],
            self.rgba[i + 3],
        ]
    }

    /// Bilinear sample at sheet position `p` (logical px) for a sheet scaled by `scale`, wrapping.
    pub fn sample(&self, px: f32, py: f32, scale: f32) -> [f32; 4] {
        let k = self.size as f32 / (self.logical * scale.max(0.01));
        let (fx, fy) = (px * k - 0.5, py * k - 0.5);
        let (x0, y0) = (fx.floor(), fy.floor());
        let (tx, ty) = (fx - x0, fy - y0);
        let n = self.size as i64;
        let w = |v: f32| (v as i64).rem_euclid(n) as u32;
        let (xa, xb, ya, yb) = (w(x0), w(x0 + 1.0), w(y0), w(y0 + 1.0));
        let (a, b, c, d) = (
            self.texel(xa, ya),
            self.texel(xb, ya),
            self.texel(xa, yb),
            self.texel(xb, yb),
        );
        std::array::from_fn(|i| {
            let top = f32::from(a[i]) * (1.0 - tx) + f32::from(b[i]) * tx;
            let bot = f32::from(c[i]) * (1.0 - tx) + f32::from(d[i]) * tx;
            (top * (1.0 - ty) + bot * ty) / 255.0
        })
    }
}

/// What a tile is made from; the cache key.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Params {
    pub kind: Kind,
    /// 0 … 1: folds and creases over the material.
    pub wrinkles: f32,
    /// Ink printed (true) or pressed into the relief (false: no colour at all).
    pub tint: bool,
    /// The largest output scale the tile is shown at (1, 1.5, 2 …): the tile's device pixels per logical pixel.
    pub device_scale: f32,
}

/// The light and the material's response, as the theme tokens carry them (`texture.*`, `light.*`).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Shading {
    /// Largest shade either way (`texture.amp`: strength × the legibility cap).
    pub amp: f32,
    pub gloss: f32,
    pub shininess: f32,
    /// Linear 0..1 RGB.
    pub ink: [f32; 3],
    /// 0 when the tint is off.
    pub ink_alpha: f32,
    /// Unit vector toward the light (x right, y down, z toward the viewer).
    pub light_dir: [f32; 3],
    /// 0..1 RGB of the light's highlights.
    pub light_color: [f32; 3],
    /// A lamp instead of `light_dir` (the wallpaper's light, K59): its position as fractions of the picture or output
    /// (x, y) and its height over the sheet in logical px (z). The direction is then taken per pixel.
    pub lamp: Option<[f32; 3]>,
}

/// The relief's colour over whatever lies under it, premultiplied RGBA (0..1) for a normal "over" blend: shade is
/// black at α (it multiplies what is under it by `1 − α`), light is `light_color` at α (a screen blend), and the ink
/// lies under the shade. A flat texel with no ink is fully transparent: the material never shifts the overall tone.
pub fn shade(t: [f32; 4], s: &Shading) -> [f32; 4] {
    let (nx, ny) = (2.0 * t[0] - 1.0, 2.0 * t[1] - 1.0);
    let nz = (1.0 - nx * nx - ny * ny).max(0.0).sqrt();
    let n = normalize([nx, ny, nz]);
    let cav = 2.0 * t[2] - 1.0;
    let l = s.light_dir;
    let diff = dot(n, l) - l[2];
    let h = normalize([l[0], l[1], l[2] + 1.0]);
    let spec = s.gloss * (dot(n, h).max(0.0).powf(s.shininess) - h[2].max(0.0).powf(s.shininess));
    let v = (s.amp * (2.0 * diff + 0.5 * cav + spec)).clamp(-s.amp, s.amp);
    let shade = if v < 0.0 {
        [0.0, 0.0, 0.0, -v]
    } else {
        [
            s.light_color[0] * v,
            s.light_color[1] * v,
            s.light_color[2] * v,
            v,
        ]
    };
    let a = t[3] * s.ink_alpha;
    let ink = [s.ink[0] * a, s.ink[1] * a, s.ink[2] * a, a];
    std::array::from_fn(|i| shade[i] + ink[i] * (1.0 - shade[3]))
}

/// The light from compass `angle` (degrees: 0 from the top, 90 from the right) at `elevation` degrees.
pub fn light_dir(angle: f32, elevation: f32) -> [f32; 3] {
    let (a, e) = (angle.to_radians(), elevation.clamp(1.0, 89.0).to_radians());
    [a.sin() * e.cos(), -a.cos() * e.cos(), e.sin()]
}

/// The texture baked into a picture (wallpaper scope): every pixel gets [`shade`] over it, the sheet registered at
/// `1 / output_scale` logical px per pixel so it lines up with the shell's sheet on the same output.
pub fn bake(
    picture: &image::RgbaImage,
    tile: &Tile,
    s: &Shading,
    output_scale: f32,
    scale: f32,
) -> image::RgbaImage {
    let mut out = picture.clone();
    let k = 1.0 / output_scale.max(0.1);
    let (w, h) = (out.width() as f32 * k, out.height() as f32 * k);
    for (x, y, px) in out.enumerate_pixels_mut() {
        let (lx, ly) = ((x as f32 + 0.5) * k, (y as f32 + 0.5) * k);
        let t = tile.sample(lx, ly, scale);
        let o = match s.lamp {
            Some([fx, fy, hz]) => {
                let sh = Shading {
                    light_dir: normalize([fx * w - lx, fy * h - ly, hz.max(1.0)]),
                    ..*s
                };
                shade(t, &sh)
            }
            None => shade(t, s),
        };
        for i in 0..3 {
            let dst = f32::from(px[i]) / 255.0;
            px[i] = ((o[i] + dst * (1.0 - o[3])).clamp(0.0, 1.0) * 255.0).round() as u8;
        }
    }
    out
}

/// Where a picture's light comes from (K59, light mode `wallpaper`): the brightest region's centre as fractions of the
/// picture (x, y), its colour (0..1 RGB, its brightest channel 1) and how much it stands out (0..1).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Spot {
    pub x: f32,
    pub y: f32,
    pub color: [f32; 3],
    pub contrast: f32,
}

/// The brightest region of `picture`: the peak of its smoothed luminance, then the light-weighted centre of the bright
/// pixels near that peak (a sun, a window, a lamp — not the average of two far-apart highlights). `None` for a picture
/// too flat to have a light of its own.
pub fn light_spot(picture: &image::RgbaImage) -> Option<Spot> {
    let small = image::imageops::thumbnail(picture, 96, 96);
    let (w, h) = (small.width() as usize, small.height() as usize);
    if w < 4 || h < 4 {
        return None;
    }
    let lum: Vec<f32> = small
        .pixels()
        .map(|p| {
            (0.2126 * f32::from(p[0]) + 0.7152 * f32::from(p[1]) + 0.0722 * f32::from(p[2])) / 255.0
        })
        .collect();
    // A 5×5 box blur: one bright pixel is noise, a bright patch is a light.
    let at = |x: isize, y: isize| {
        lum[(y.clamp(0, h as isize - 1) as usize) * w + x.clamp(0, w as isize - 1) as usize]
    };
    let blur: Vec<f32> = (0..h * w)
        .map(|i| {
            let (x, y) = ((i % w) as isize, (i / w) as isize);
            let mut sum = 0.0;
            for dy in -2..=2 {
                for dx in -2..=2 {
                    sum += at(x + dx, y + dy);
                }
            }
            sum / 25.0
        })
        .collect();
    let mut sorted = blur.clone();
    sorted.sort_by(f32::total_cmp);
    let (median, p97) = (sorted[sorted.len() / 2], sorted[sorted.len() * 97 / 100]);
    let contrast = p97 - median;
    if contrast < 0.12 {
        return None;
    }
    let peak = (0..blur.len()).max_by(|a, b| blur[*a].total_cmp(&blur[*b]))?;
    let (px, py) = ((peak % w) as f32, (peak / w) as f32);
    let reach = 0.25 * w.max(h) as f32;
    let (mut sx, mut sy, mut sw) = (0.0, 0.0, 0.0);
    let mut color = [0.0f32; 3];
    for (i, b) in blur.iter().enumerate() {
        let (x, y) = ((i % w) as f32, (i / w) as f32);
        if *b < p97 || ((x - px).powi(2) + (y - py).powi(2)).sqrt() > reach {
            continue;
        }
        let wt = (b - p97 + 0.02).powi(2);
        sx += x * wt;
        sy += y * wt;
        sw += wt;
        let p = small.get_pixel(i as u32 % w as u32, i as u32 / w as u32);
        for c in 0..3 {
            color[c] += f32::from(p[c]) / 255.0 * wt;
        }
    }
    if sw <= 0.0 {
        return None;
    }
    let max = color.iter().copied().fold(1e-6, f32::max);
    Some(Spot {
        x: (sx / sw + 0.5) / w as f32,
        y: (sy / sw + 0.5) / h as f32,
        color: color.map(|c| c / max),
        contrast: contrast.min(1.0),
    })
}

/// A lit swatch of `px` × `px` on `base` (0..1 RGB): Settings' material cards.
pub fn preview(tile: &Tile, s: &Shading, base: [f32; 3], px: u32, scale: f32) -> image::RgbaImage {
    let b = image::Rgba([
        (base[0] * 255.0) as u8,
        (base[1] * 255.0) as u8,
        (base[2] * 255.0) as u8,
        255,
    ]);
    let ground = image::RgbaImage::from_pixel(px, px, b);
    bake(&ground, tile, s, 1.0, scale)
}

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("texture cache: {0}")]
    Io(#[from] std::io::Error),
    #[error("texture image: {0}")]
    Image(#[from] image::ImageError),
}

/// The tile for `p` as a PNG in `cache_dir`, generated once (atomic write) and loaded after: the file name is the cache
/// key, so a stale file can never be shown for other parameters. A cached file that fails to decode is generated again.
pub fn tile_file(cache_dir: &Path, p: &Params) -> Result<(PathBuf, Tile), Error> {
    let name = format!(
        "{}-w{:03}-{}-s{:03}-v{}.png",
        p.kind.name(),
        (p.wrinkles.clamp(0.0, 1.0) * 100.0).round() as u32,
        if p.tint { "ink" } else { "plain" },
        (p.device_scale * 100.0).round() as u32,
        generate::VERSION,
    );
    let path = cache_dir.join(name);
    let ink = ink_path(&path);
    if path.is_file()
        && let Ok(img) = image::open(&path)
    {
        let rgb = img.to_rgb8();
        let (side, logical) = generate::geometry(p.device_scale);
        if rgb.width() == side && rgb.height() == side {
            // The ink map is optional (none for an ink-free tile); a missing or unreadable one means no ink.
            let alpha = image::open(&ink).ok().map(|i| i.to_rgba8());
            let mut rgba = Vec::with_capacity((side * side * 4) as usize);
            for (i, px) in rgb.pixels().enumerate() {
                let a = alpha.as_ref().map_or(0, |a| {
                    let (x, y) = (i as u32 % side, i as u32 / side);
                    a.get_pixel(x, y)[3]
                });
                rgba.extend_from_slice(&[px[0], px[1], px[2], a]);
            }
            let tile = Tile {
                size: side,
                logical,
                rgba,
            };
            return Ok((path, tile));
        }
    }
    let tile = generate(p);
    std::fs::create_dir_all(cache_dir)?;
    // Two files (contract rows 280, 281): Qt uploads textures premultiplied, so the normals cannot share a texel with
    // an alpha that is mostly 0. The relief is an opaque RGB map; the ink, when there is any, an RGBA map of white with
    // the coverage in alpha.
    let rgb: Vec<u8> = tile
        .rgba
        .chunks_exact(4)
        .flat_map(|c| [c[0], c[1], c[2]])
        .collect();
    let tmp = path.with_extension("png.tmp");
    image::RgbImage::from_raw(tile.size, tile.size, rgb)
        .expect("tile size matches its buffer")
        .save_with_format(&tmp, image::ImageFormat::Png)?;
    if tile.rgba.chunks_exact(4).any(|c| c[3] > 0) {
        let white: Vec<u8> = tile
            .rgba
            .chunks_exact(4)
            .flat_map(|c| [255, 255, 255, c[3]])
            .collect();
        let tmp_ink = ink.with_extension("png.tmp");
        image::RgbaImage::from_raw(tile.size, tile.size, white)
            .expect("tile size matches its buffer")
            .save_with_format(&tmp_ink, image::ImageFormat::Png)?;
        std::fs::rename(&tmp_ink, &ink)?;
    } else {
        let _ = std::fs::remove_file(&ink);
    }
    std::fs::rename(&tmp, &path)?;
    Ok((path, tile))
}

/// The ink map beside a tile file (`<name>-ink.png`); it exists only when the tile prints ink.
pub fn ink_path(tile_file: &Path) -> PathBuf {
    let stem = tile_file
        .file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_default();
    tile_file.with_file_name(format!("{stem}-ink.png"))
}

/// How each kind reflects light and which ink it carries.
pub fn material(kind: Kind) -> Material {
    let m = |gloss, shininess, ink_role, ink_alpha| Material {
        gloss,
        shininess,
        ink_role,
        ink_alpha,
    };
    match kind {
        Kind::Paper => m(0.0, 8.0, InkRole::OnSurface, 0.06),
        // The dots are 2.2 px across: a little stronger than the 1 px rulings, so they hold their colour at 1:1.
        Kind::PaperDots => m(0.0, 8.0, InkRole::Secondary, 0.45),
        Kind::PaperLines | Kind::PaperGrid => m(0.0, 8.0, InkRole::Secondary, 0.35),
        Kind::Fabric => m(0.05, 6.0, InkRole::OnSurface, 0.08),
        Kind::Wool => m(0.0, 4.0, InkRole::None, 0.0),
        Kind::Stone => m(0.1, 12.0, InkRole::OnSurface, 0.1),
        // Print is the busiest pattern behind text: its ink stays a quiet grey at the default strength.
        Kind::Halftone => m(0.0, 8.0, InkRole::OnSurface, 0.16),
        Kind::Metal => m(0.6, 40.0, InkRole::None, 0.0),
        Kind::Leather => m(0.3, 18.0, InkRole::None, 0.0),
        Kind::Wood => m(0.12, 14.0, InkRole::OnSurface, 0.12),
        // Oil paint is glossy where the brush left ridges; its pigment varies a little in tone.
        Kind::Paint => m(0.3, 24.0, InkRole::OnSurface, 0.06),
    }
}

fn dot(a: [f32; 3], b: [f32; 3]) -> f32 {
    a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
}

fn normalize(v: [f32; 3]) -> [f32; 3] {
    let l = dot(v, v).sqrt().max(1e-6);
    [v[0] / l, v[1] / l, v[2] / l]
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lit() -> Shading {
        Shading {
            amp: 0.1,
            gloss: 0.0,
            shininess: 8.0,
            ink: [0.2, 0.3, 0.6],
            ink_alpha: 0.0,
            light_dir: light_dir(315.0, 40.0),
            light_color: [1.0, 1.0, 1.0],
            lamp: None,
        }
    }

    #[test]
    fn a_flat_texel_leaves_the_ground_alone() {
        let o = shade([0.5, 0.5, 0.5, 0.0], &lit());
        assert!(o.iter().all(|v| v.abs() < 1e-3), "{o:?}");
    }

    #[test]
    fn a_slope_toward_the_light_brightens_and_away_darkens() {
        // Light from the top left: a normal tilted up-left faces it.
        let toward = shade([0.3, 0.3, 0.5, 0.0], &lit());
        let away = shade([0.7, 0.7, 0.5, 0.0], &lit());
        assert!(toward[3] > 0.0 && toward[0] > 0.0, "{toward:?}");
        assert!(away[3] > 0.0 && away[0] == 0.0, "{away:?}");
        assert!(toward[3] <= 0.1 + 1e-6 && away[3] <= 0.1 + 1e-6);
    }

    #[test]
    fn the_light_spot_is_the_bright_patch_and_flat_pictures_have_none() {
        let mut img = image::RgbaImage::from_pixel(160, 90, image::Rgba([30, 40, 60, 255]));
        // A warm sun up right, and a lone bright pixel down left (noise).
        for y in 10..26 {
            for x in 110..130 {
                img.put_pixel(x, y, image::Rgba([255, 210, 150, 255]));
            }
        }
        img.put_pixel(5, 80, image::Rgba([255, 255, 255, 255]));
        let s = light_spot(&img).expect("a sun");
        assert!(
            (s.x - 0.75).abs() < 0.08 && (s.y - 0.2).abs() < 0.1,
            "{s:?}"
        );
        assert!(s.color[0] > s.color[2], "warm: {s:?}");
        let flat = image::RgbaImage::from_pixel(160, 90, image::Rgba([120, 120, 120, 255]));
        assert_eq!(light_spot(&flat), None);
    }

    #[test]
    fn light_dir_is_a_unit_vector_from_the_compass() {
        let top = light_dir(0.0, 45.0);
        assert!(top[1] < 0.0 && top[0].abs() < 1e-6);
        let right = light_dir(90.0, 45.0);
        assert!(right[0] > 0.0);
        assert!((dot(right, right) - 1.0).abs() < 1e-5);
    }

    #[test]
    fn every_kind_generates_a_seamless_deterministic_tile() {
        for kind in Kind::ALL {
            let p = Params {
                kind,
                wrinkles: 0.3,
                tint: true,
                device_scale: 1.0,
            };
            let a = generate(&p);
            assert_eq!(a.rgba.len(), (a.size * a.size * 4) as usize, "{kind:?}");
            assert_eq!(a, generate(&p), "{kind:?} is not deterministic");
            assert_eq!(Kind::parse(kind.name()), Some(kind));
        }
    }

    #[test]
    fn tile_files_are_cached_by_their_parameters() {
        let dir = tempfile::tempdir().unwrap();
        let p = Params {
            kind: Kind::Paper,
            wrinkles: 0.0,
            tint: false,
            device_scale: 1.0,
        };
        let (a, _) = tile_file(dir.path(), &p).unwrap();
        let (b, _) = tile_file(dir.path(), &Params { tint: true, ..p }).unwrap();
        assert!(a.is_file() && b.is_file() && a != b);
    }
}
