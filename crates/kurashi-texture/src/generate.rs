//! The generators: a height field and an ink field per kind, turned into the tile layout of the crate docs.
//!
//! Heights are logical pixels, so a bump keeps its size at every device scale; the ink is coverage 0..1. The logical
//! tile is 48 × k logical px (k = 10, fewer when a device side would pass 1024 px): every pattern period divides it
//! (rulings 24, print 16, weave 4, knit 16 and 12, facets 24, cells 20 and 40), so the tile repeats without a seam. Each
//! kind is built from its own seed. The per-texel passes run in bands of rows on several threads ([`rows`], I171): every
//! texel is computed from its own position alone, and the marks (fibres, strokes) are laid in order on one thread, so the
//! same parameters give the same bytes on every run and at every thread count (the cache in [`crate::tile_file`] relies
//! on it).

use crate::{Kind, Params, Tile};
use crate::{brush, cracks, leather, metal, paint, paper, print, stone, weave, wood, wrinkle};

/// Bumped whenever the generated bytes change, so cached tiles of an older generator are not reused.
pub const VERSION: u32 = 7;

/// Every tile is a multiple of this many logical px (see the module docs).
const UNIT: u32 = 48;
/// The largest device side a tile is generated at (the GPU budget, DESIGN-SYSTEM "Texture and light").
const MAX_PX: u32 = 1024;

/// The device side in px and the logical px a tile covers, for these parameters. `device_scale` is taken to 0.01 and
/// clamped to 1…4, as the cache name quantises it.
pub fn geometry(device_scale: f32) -> (u32, f32) {
    let s = ((device_scale.clamp(1.0, 4.0) * 100.0).round() / 100.0).max(1.0);
    let mut k = 10;
    while k > 1 && (UNIT * k) as f32 * s > MAX_PX as f32 {
        k -= 1;
    }
    let logical = (UNIT * k) as f32;
    let size = ((logical * s).round() as u32).min(MAX_PX);
    (size, logical)
}

/// The texel grid of a tile: copied into the passes that run in bands of rows.
#[derive(Clone, Copy, Debug)]
pub struct Grid {
    /// Side in device px.
    pub n: usize,
    /// Device px per logical px.
    pub scale: f32,
}

impl Grid {
    /// Logical position of texel `i` along an axis (texel centres).
    pub fn at(&self, i: usize) -> f32 {
        (i as f32 + 0.5) / self.scale
    }

    /// Tile position, 0..1, of texel `i` along an axis.
    pub fn uv(&self, i: usize) -> f32 {
        (i as f32 + 0.5) / self.n as f32
    }
}

/// The heights and ink of one tile, row-major, `n` × `n` texels.
pub struct Field {
    /// Side in device px.
    pub n: usize,
    /// Logical px the tile covers.
    pub logical: f32,
    /// Device px per logical px.
    pub scale: f32,
    /// Threads for the per-texel passes.
    pub threads: usize,
    /// Height in logical px.
    pub h: Vec<f32>,
    /// Ink coverage, 0..1.
    pub ink: Vec<f32>,
}

impl Field {
    fn new(n: usize, logical: f32, threads: usize) -> Field {
        Field {
            n,
            logical,
            scale: n as f32 / logical,
            threads: threads.max(1),
            h: vec![0.0; n * n],
            ink: vec![0.0; n * n],
        }
    }

    pub fn grid(&self) -> Grid {
        Grid {
            n: self.n,
            scale: self.scale,
        }
    }
}

/// `g(y, row)` for every one of the `n` rows of `out` (row-major, `out.len() / n` values a row), in bands of rows on
/// `threads` threads (I171). `g` computes a row from its own position only, so the result is the same at every thread
/// count.
pub fn rows<T: Send>(n: usize, threads: usize, out: &mut [T], g: impl Fn(usize, &mut [T]) + Sync) {
    let w = out.len() / n.max(1);
    if threads <= 1 || n < 2 * threads {
        for (y, row) in out.chunks_mut(w).enumerate() {
            g(y, row);
        }
        return;
    }
    let band = n.div_ceil(threads);
    std::thread::scope(|scope| {
        for (b, chunk) in out.chunks_mut(band * w).enumerate() {
            let g = &g;
            scope.spawn(move || {
                for (r, row) in chunk.chunks_mut(w).enumerate() {
                    g(b * band + r, row);
                }
            });
        }
    });
}

/// [`rows`] over two row-major buffers of the same rows at once (the heights and the ink).
pub fn rows2<A: Send, B: Send>(
    n: usize,
    threads: usize,
    a: &mut [A],
    b: &mut [B],
    g: impl Fn(usize, &mut [A], &mut [B]) + Sync,
) {
    let (wa, wb) = (a.len() / n.max(1), b.len() / n.max(1));
    if threads <= 1 || n < 2 * threads {
        for (y, (ra, rb)) in a.chunks_mut(wa).zip(b.chunks_mut(wb)).enumerate() {
            g(y, ra, rb);
        }
        return;
    }
    let band = n.div_ceil(threads);
    std::thread::scope(|scope| {
        for (k, (ca, cb)) in a
            .chunks_mut(band * wa)
            .zip(b.chunks_mut(band * wb))
            .enumerate()
        {
            let g = &g;
            scope.spawn(move || {
                for (r, (ra, rb)) in ca.chunks_mut(wa).zip(cb.chunks_mut(wb)).enumerate() {
                    g(k * band + r, ra, rb);
                }
            });
        }
    });
}

/// The threads a tile is generated on: the machine's, at most 8 (a tile is a one-off job on a blocking thread).
fn default_threads() -> usize {
    std::thread::available_parallelism()
        .map(|n| n.get())
        .unwrap_or(1)
        .clamp(1, 8)
}

/// The seed of a kind's material: fixed per kind, so every surface shows the same sheet.
fn seed_of(kind: Kind) -> u64 {
    let mut z = 0x6B75_7261_7368_6900u64 ^ (kind as u64 + 1).wrapping_mul(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z ^ (z >> 27)
}

/// The tile for `p`: deterministic, seamless, and the same bytes for the same parameters.
pub fn generate(p: &Params) -> Tile {
    generate_threads(p, default_threads())
}

/// [`generate`] on `threads` threads: the same bytes at every count (the tests compare one against many).
pub fn generate_threads(p: &Params, threads: usize) -> Tile {
    let (size, logical) = geometry(p.device_scale);
    let mut f = Field::new(size as usize, logical, threads);
    let seed = seed_of(p.kind);
    let tint = p.tint;
    match p.kind {
        Kind::Paper => paper::plain(&mut f, seed, tint),
        Kind::PaperDots => ruled(&mut f, seed, paper::Ruling::Dots, tint),
        Kind::PaperLines => ruled(&mut f, seed, paper::Ruling::Lines, tint),
        Kind::PaperGrid => ruled(&mut f, seed, paper::Ruling::Grid, tint),
        Kind::Fabric => weave::fabric(&mut f, seed, tint),
        Kind::Wool => weave::knit(&mut f, seed),
        Kind::Stone => stone::stone(&mut f, seed, tint),
        Kind::Halftone => print::halftone(&mut f, seed, tint),
        Kind::Metal => metal::brushed(&mut f, seed),
        Kind::Leather => leather::leather(&mut f, seed),
        Kind::Wood => wood::boards(&mut f, seed, tint),
        Kind::Paint => paint::oil(&mut f, seed, tint),
        Kind::Brush => brush::brush(&mut f, seed, tint),
    }
    let wrinkles = (p.wrinkles.clamp(0.0, 1.0) * 100.0).round() / 100.0;
    if wrinkles > 0.0 {
        wrinkle::apply(&mut f, seed, wrinkles, wrinkle::depth(p.kind));
    }
    // K61: the cracks after the wrinkles (a crack runs through a fold); 0 leaves the bytes alone.
    let amount = (p.cracks.clamp(0.0, 1.0) * 100.0).round() / 100.0;
    if amount > 0.0 {
        cracks::apply(&mut f, seed, amount, p.crack_style);
    }
    finish(f)
}

/// Paper with its rulings (printed or pressed in); the sheet itself carries no pigment under them.
fn ruled(f: &mut Field, seed: u64, which: paper::Ruling, tint: bool) {
    paper::ruled_sheet(f, seed);
    paper::rulings(f, which, tint);
}

/// Normals, cavity and ink into the tile layout: R, G the surface normal's x and y (image axes, `x` right, `y` down),
/// B the cavity (crevice −1 … crest +1), A the ink.
///
/// I170: the slope is the five-point derivative, `(8 (h₊₁ − h₋₁) − (h₊₂ − h₋₂)) / 12`: detail of a 2.5–3 px period keeps
/// about 1.6 times the slope the plain central difference left it (bristle tracks, fine weave, hairline cracks), while
/// broad slopes read as before.
fn finish(f: Field) -> Tile {
    let n = f.n;
    let s = f.scale;
    let len = (n * n) as f32;
    let mean = f.h.iter().sum::<f32>() / len;
    let low = box_blur(&f.h, n, (2.5 * s).round().max(1.0) as isize, f.threads);
    let hi: Vec<f32> = f.h.iter().zip(&low).map(|(h, l)| h - l).collect();
    let sd_h = (f.h.iter().map(|h| (h - mean) * (h - mean)).sum::<f32>() / len)
        .sqrt()
        .max(1e-6);
    let sd_c = (hi.iter().map(|c| c * c).sum::<f32>() / len)
        .sqrt()
        .max(1e-6);
    let (h, ink) = (&f.h, &f.ink);
    let mut rgba = vec![0u8; n * n * 4];
    rows(n, f.threads, &mut rgba, |y, row| {
        let at = |x: isize, y: isize| h[wrap(n, y) * n + wrap(n, x)];
        let yi = y as isize;
        for x in 0..n {
            let i = y * n + x;
            let xi = x as isize;
            // In logical px: one device px is 1 / scale logical px apart.
            let gx = (8.0 * (at(xi + 1, yi) - at(xi - 1, yi)) - (at(xi + 2, yi) - at(xi - 2, yi)))
                * s
                / 12.0;
            let gy = (8.0 * (at(xi, yi + 1) - at(xi, yi - 1)) - (at(xi, yi + 2) - at(xi, yi - 2)))
                * s
                / 12.0;
            let k = 1.0 / (1.0 + gx * gx + gy * gy).sqrt();
            let cav = 0.5 * (h[i] - mean) / (2.0 * sd_h) + 0.5 * hi[i] / (2.0 * sd_c);
            let o = x * 4;
            row[o] = enc(-gx * k);
            row[o + 1] = enc(-gy * k);
            row[o + 2] = enc(cav);
            row[o + 3] = (ink[i].clamp(0.0, 1.0) * 255.0).round() as u8;
        }
    });
    // K61: the heights from the tile's low to its high, robustly: the 0.5th to the 99.5th percentile, clamped, so a lone
    // spike (a fibre crossing, a crack's deepest point) does not flatten the rest of the map.
    let (lo, top) = percentiles(h, 0.005, 0.995);
    let relief = (top - lo).max(0.0);
    let height = h
        .iter()
        .map(|v| {
            if relief > 1e-6 {
                ((v - lo) / relief * 255.0).clamp(0.0, 255.0).round() as u8
            } else {
                0
            }
        })
        .collect();
    Tile {
        size: n as u32,
        logical: f.logical,
        rgba,
        height,
        relief,
    }
}

/// The values at fractions `a` and `b` of the sorted heights.
fn percentiles(h: &[f32], a: f32, b: f32) -> (f32, f32) {
    let mut v = h.to_vec();
    let last = v.len() - 1;
    let ia = (a * last as f32).round() as usize;
    let ib = (b * last as f32).round() as usize;
    let lo = *v.select_nth_unstable_by(ia, f32::total_cmp).1;
    let hi = *v.select_nth_unstable_by(ib, f32::total_cmp).1;
    (lo, hi)
}

/// A value in −1…1 as a byte (0 → 128).
fn enc(v: f32) -> u8 {
    ((v.clamp(-1.0, 1.0) * 0.5 + 0.5) * 255.0).round() as u8
}

pub(crate) fn wrap(n: usize, v: isize) -> usize {
    v.rem_euclid(n as isize) as usize
}

/// Mean over a `(2r + 1)`² window, wrapping at the edges (separable; rows in parallel).
pub(crate) fn box_blur(h: &[f32], n: usize, r: isize, threads: usize) -> Vec<f32> {
    let k = 1.0 / (2 * r + 1) as f32;
    let mut tmp = vec![0f32; n * n];
    rows(n, threads, &mut tmp, |y, row| {
        for (x, v) in row.iter_mut().enumerate() {
            let s: f32 = (-r..=r).map(|d| h[y * n + wrap(n, x as isize + d)]).sum();
            *v = s * k;
        }
    });
    let mut out = vec![0f32; n * n];
    rows(n, threads, &mut out, |y, row| {
        for (x, v) in row.iter_mut().enumerate() {
            let s: f32 = (-r..=r).map(|d| tmp[wrap(n, y as isize + d) * n + x]).sum();
            *v = s * k;
        }
    });
    out
}
