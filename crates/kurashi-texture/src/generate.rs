//! The generators: a height field and an ink field per kind, turned into the tile layout of the crate docs.
//!
//! Heights are logical pixels, so a bump keeps its size at every device scale; the ink is coverage 0..1. The logical
//! tile is 48 × k logical px (k = 10, fewer when a device side would pass 1024 px): every pattern period divides it
//! (rulings 24, print 16, weave 6, knit 8, facets 24, cells 20 and 40), so the tile repeats without a seam. Each kind
//! is built from its own seed, and everything is single-threaded f32 arithmetic: the same parameters give the same bytes
//! on every run (the cache in [`crate::tile_file`] relies on it).

use crate::{Kind, Params, Tile};
use crate::{leather, metal, paper, print, stone, weave, wood, wrinkle};

/// Bumped whenever the generated bytes change, so cached tiles of an older generator are not reused.
pub const VERSION: u32 = 1;

/// Every tile is a multiple of this many logical px (see the module docs).
const UNIT: u32 = 48;
/// The largest device side a tile is generated at (the GPU budget, DESIGN-SYSTEM "Texture and light").
const MAX_PX: u32 = 1024;

/// The device side in px and the logical px a tile covers, for these parameters. `device_scale` is taken to 0.01 and
/// clamped to 1…4, as the cache name quantises it.
pub fn geometry(device_scale: f32) -> (u32, f32) {
    let s = ((device_scale.clamp(1.0, 4.0) * 100.0).round() / 100.0).max(1.0);
    let mut k = 10;
    while k > 1 && (UNIT * k) as f32 * s > MAX_PX as f32 {
        k -= 1;
    }
    let logical = (UNIT * k) as f32;
    let size = ((logical * s).round() as u32).min(MAX_PX);
    (size, logical)
}

/// The heights and ink of one tile, row-major, `n` × `n` texels.
pub struct Field {
    /// Side in device px.
    pub n: usize,
    /// Logical px the tile covers.
    pub logical: f32,
    /// Device px per logical px.
    pub scale: f32,
    /// Height in logical px.
    pub h: Vec<f32>,
    /// Ink coverage, 0..1.
    pub ink: Vec<f32>,
}

impl Field {
    fn new(n: usize, logical: f32) -> Field {
        Field {
            n,
            logical,
            scale: n as f32 / logical,
            h: vec![0.0; n * n],
            ink: vec![0.0; n * n],
        }
    }

    /// Logical position of texel `i` along an axis (texel centres).
    pub fn at(&self, i: usize) -> f32 {
        (i as f32 + 0.5) / self.scale
    }

    /// Tile position, 0..1, of texel `i` along an axis.
    pub fn uv(&self, i: usize) -> f32 {
        (i as f32 + 0.5) / self.n as f32
    }
}

/// The seed of a kind's material: fixed per kind, so every surface shows the same sheet.
fn seed_of(kind: Kind) -> u64 {
    let mut z = 0x6B75_7261_7368_6900u64 ^ (kind as u64 + 1).wrapping_mul(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z ^ (z >> 27)
}

/// The tile for `p`: deterministic, seamless, and the same bytes for the same parameters.
pub fn generate(p: &Params) -> Tile {
    let (size, logical) = geometry(p.device_scale);
    let mut f = Field::new(size as usize, logical);
    let seed = seed_of(p.kind);
    let tint = p.tint;
    match p.kind {
        Kind::Paper => paper::sheet(&mut f, seed, tint),
        Kind::PaperDots => ruled(&mut f, seed, paper::Ruling::Dots, tint),
        Kind::PaperLines => ruled(&mut f, seed, paper::Ruling::Lines, tint),
        Kind::PaperGrid => ruled(&mut f, seed, paper::Ruling::Grid, tint),
        Kind::Fabric => weave::fabric(&mut f, seed, tint),
        Kind::Wool => weave::knit(&mut f, seed),
        Kind::Stone => stone::stone(&mut f, seed, tint),
        Kind::Halftone => print::halftone(&mut f, seed, tint),
        Kind::Metal => metal::brushed(&mut f, seed),
        Kind::Leather => leather::leather(&mut f, seed),
        Kind::Wood => wood::planks(&mut f, seed, tint),
    }
    let wrinkles = (p.wrinkles.clamp(0.0, 1.0) * 100.0).round() / 100.0;
    if wrinkles > 0.0 {
        wrinkle::apply(&mut f, seed, wrinkles, wrinkle::depth(p.kind));
    }
    finish(f)
}

/// Paper with its rulings (printed or pressed in); the sheet itself carries no pigment under them.
fn ruled(f: &mut Field, seed: u64, which: paper::Ruling, tint: bool) {
    paper::sheet(f, seed, false);
    paper::rulings(f, which, tint);
}

/// Normals, cavity and ink into the tile layout: R, G the surface normal's x and y (image axes, `x` right, `y` down),
/// B the cavity (crevice −1 … crest +1), A the ink.
fn finish(f: Field) -> Tile {
    let n = f.n;
    let s = f.scale;
    let len = (n * n) as f32;
    let mean = f.h.iter().sum::<f32>() / len;
    let low = box_blur(&f.h, n, (2.5 * s).round().max(1.0) as isize);
    let hi: Vec<f32> = f.h.iter().zip(&low).map(|(h, l)| h - l).collect();
    let sd_h = (f.h.iter().map(|h| (h - mean) * (h - mean)).sum::<f32>() / len)
        .sqrt()
        .max(1e-6);
    let sd_c = (hi.iter().map(|c| c * c).sum::<f32>() / len)
        .sqrt()
        .max(1e-6);
    let at = |x: isize, y: isize| f.h[wrap(n, y) * n + wrap(n, x)];
    let mut rgba = vec![0u8; n * n * 4];
    for y in 0..n {
        for x in 0..n {
            let i = y * n + x;
            let (xi, yi) = (x as isize, y as isize);
            // Central differences in logical px: one device px is 1 / scale logical px apart.
            let gx = (at(xi + 1, yi) - at(xi - 1, yi)) * s * 0.5;
            let gy = (at(xi, yi + 1) - at(xi, yi - 1)) * s * 0.5;
            let k = 1.0 / (1.0 + gx * gx + gy * gy).sqrt();
            let cav = 0.5 * (f.h[i] - mean) / (2.0 * sd_h) + 0.5 * hi[i] / (2.0 * sd_c);
            let o = i * 4;
            rgba[o] = enc(-gx * k);
            rgba[o + 1] = enc(-gy * k);
            rgba[o + 2] = enc(cav);
            rgba[o + 3] = (f.ink[i].clamp(0.0, 1.0) * 255.0).round() as u8;
        }
    }
    Tile {
        size: n as u32,
        logical: f.logical,
        rgba,
    }
}

/// A value in −1…1 as a byte (0 → 128).
fn enc(v: f32) -> u8 {
    ((v.clamp(-1.0, 1.0) * 0.5 + 0.5) * 255.0).round() as u8
}

fn wrap(n: usize, v: isize) -> usize {
    v.rem_euclid(n as isize) as usize
}

/// Mean over a `(2r + 1)`² window, wrapping at the edges (separable).
pub(crate) fn box_blur(h: &[f32], n: usize, r: isize) -> Vec<f32> {
    let k = 1.0 / (2 * r + 1) as f32;
    let mut tmp = vec![0f32; n * n];
    for y in 0..n {
        for x in 0..n {
            let s: f32 = (-r..=r).map(|d| h[y * n + wrap(n, x as isize + d)]).sum();
            tmp[y * n + x] = s * k;
        }
    }
    let mut out = vec![0f32; n * n];
    for y in 0..n {
        for x in 0..n {
            let s: f32 = (-r..=r).map(|d| tmp[wrap(n, y as isize + d) * n + x]).sum();
            out[y * n + x] = s * k;
        }
    }
    out
}
